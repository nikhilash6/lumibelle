async function configure(page) {
  await page.goto('/settings/ai');
  const connections = page.getByRole('tab', { name: 'Connections', exact: true });
  await expect(async () => { await connections.click(); await expect(connections).toHaveAttribute('aria-selected', 'true'); }).toPass();
  const codex = page.getByRole('tab', { name: 'Codex', exact: true });
  await expect(async () => { await codex.click(); await expect(codex).toHaveAttribute('aria-selected', 'true'); }).toPass();
  await page.getByRole('checkbox', { name: 'Enable Codex', exact: true }).check();
  const card = page.locator('form').filter({ has: page.getByRole('heading', { name: 'Codex', exact: true }) });
  await card.getByRole('button', { name: 'Check connection', exact: true }).click();
  await expect(card).toContainText('qa@example.test');
  await card.getByRole('button', { name: 'Save Codex connection', exact: true }).click();
  await expect(page.locator('.settings-feedback')).toContainText('Codex connection saved');
  await expect(card).toContainText('85% remaining');
  await expect(card).toContainText('Supported by this CLI');
  await expect(card.locator('.codex-usage-window')).toHaveCount(1);
  await expect(card.locator('.codex-usage-window')).toContainText('5-hour');
  await expect(card.locator('.codex-usage')).not.toContainText('Unavailable');
  await page.getByRole('tab', { name: 'Text models', exact: true }).click();
  await expect(page.getByRole('tablist', { name: 'Text model providers' }).getByRole('tab', { name: 'Codex', exact: true })).toHaveAttribute('aria-selected', 'true');
  await page.getByText('Codex defaults', { exact: true }).click();
  await page.getByLabel('Default Codex reasoning effort', { exact: true }).selectOption('high');
  await page.getByRole('button', { name: 'Save default effort', exact: true }).click();
  await expect(page.locator('.settings-feedback')).toContainText('Default Codex reasoning effort saved');
  await page.getByRole('button', { name: 'Star Codex QA', exact: true }).click();
  await page.getByRole('tab', { name: 'Image models', exact: true }).click();
  const workflows = page.getByRole('tablist', { name: 'Image workflows' });
  await workflows.getByRole('tab', { name: 'Codex Images', exact: true }).click();
  await expect(page.getByLabel('Codex agent model', { exact: true })).toBeVisible();
  await expect(page.locator('#codex-image-model-help')).toContainText('Image model: managed by Codex');
  await page.getByRole('button', { name: 'Refresh Codex models', exact: true }).click();
  await page.locator('#codex-image-model').selectOption('mock-codex');
  await page.locator('#codex-image-effort').selectOption('high');
  await page.getByRole('button', { name: 'Save Codex Images', exact: true }).click();
  await expect(page.locator('.settings-feedback')).toContainText('Codex Images saved');
  // Saving a workflow does not make it the default; Defaults does.
  await workflows.getByRole('tab', { name: 'Defaults', exact: true }).click();
  await page.locator('#image-workflow').selectOption('CodexImages');
  await page.getByRole('button', { name: 'Save image defaults', exact: true }).click();
  await expect(page.locator('.settings-feedback')).toContainText('Image defaults saved');
}
