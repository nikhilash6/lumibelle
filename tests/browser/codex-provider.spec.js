test('A Codex usage-limit failure pauses the queue until an explicit resume and queued work survives navigation', async ({ page, request }) => {
  await configure(page); const { id } = await asset(page, request);
  // Codex reports the exhausted limit by failing the turn; nothing is blocked up front.
  await request.post('/fixtures/codex-quota?used=100');
  await page.locator('#image-prompt').fill('A small bird.');
  await page.getByRole('button', { name: 'Generate images', exact: true }).click();
  await page.locator('.ai-activity-trigger').click();
  const activity = page.getByRole('dialog', { name: 'AI activity', exact: true });
  await expect(activity.getByRole('button', { name: 'Resume queue Codex', exact: true })).toBeVisible();
  await activity.getByRole('button', { name: 'Close AI activity' }).click();
  // Generate cleared the composer, so the next request is written again.
  await page.locator('#image-prompt').fill('A small bird.');
  await page.getByRole('button', { name: 'Generate images', exact: true }).click();
  await expect(page.locator('.generation-panel .ai-queue-wait')).toBeVisible();
  await request.post('/fixtures/codex-quota?used=15');
  await page.goto('/'); await page.locator('.ai-activity-trigger').click();
  await activity.getByRole('button', { name: 'Resume queue Codex', exact: true }).click();
  await expect.poll(async () => (await (await request.get(`/fixtures/${id}`)).json()).assets.assets[0].images.length).toBe(2);
});


